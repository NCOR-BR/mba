function toggleSidebar() {
  const aside = document.querySelector(".sidebar");
  if (aside.classList.contains("active")) {
    aside.classList.remove("active");
  } else {
    aside.classList.add("active");
  }
}

function filtrarCategoria(categoria, botaoClicado) {
  const botoes = document.querySelectorAll(".btn-filtro");
  botoes.forEach((btn) => btn.classList.remove("ativo"));
  botaoClicado.classList.add("ativo");

  const publicacoes = document.querySelectorAll(".pub-item");
  const noPub = document.querySelector(".noPub");

  let temAlgumaVisivel = false;

  publicacoes.forEach((pub) => {
    let catItem = pub.getAttribute("data-categoria");

    if (categoria === "todas") {
      if (catItem === "apresentacao") {
        pub.style.display = "none";
      } else {
        pub.style.display = "";
        temAlgumaVisivel = true;
      }
    } else {
      if (catItem === categoria) {
        pub.style.display = "";
        temAlgumaVisivel = true;
      } else {
        pub.style.display = "none";
      }
    }
  });

  if (!temAlgumaVisivel) {
    if (noPub) noPub.style.display = "block";
  } else {
    if (noPub) noPub.style.display = "none";
  }

  document.getElementById("buscaPublicacao").value = "";
  verificarGruposVazios();
}

function filtrarPublicacoes() {
  const input = document.getElementById("buscaPublicacao");
  const filtro = input.value.toLowerCase();
  const publicacoes = document.querySelectorAll(".pub-item");
  const noPub = document.querySelector(".noPub");

  let temAlgumaVisivel = false;

  publicacoes.forEach((pub) => {
    const textoPub = pub.textContent.toLowerCase();

    if (textoPub.includes(filtro)) {
      pub.style.display = "";
      temAlgumaVisivel = true;
    } else {
      pub.style.display = "none";
    }
  });

  if (!temAlgumaVisivel) {
    if (noPub) noPub.style.display = "block";
  } else {
    if (noPub) noPub.style.display = "none";
  }

  const botoes = document.querySelectorAll(".btn-filtro");
  botoes.forEach((btn) => btn.classList.remove("ativo"));
  botoes[0].classList.add("ativo");

  verificarGruposVazios();
}

function verificarGruposVazios() {
  const grupos = document.querySelectorAll(".grupo-publicacoes");

  grupos.forEach((grupo) => {
    const publicacoesDesteGrupo = Array.from(
      grupo.querySelectorAll(".pub-item"),
    );

    const temVisivel = publicacoesDesteGrupo.some(
      (pub) => pub.style.display !== "none",
    );

    if (temVisivel) {
      grupo.style.display = "block";
    } else {
      grupo.style.display = "none";
    }
  });
}

window.addEventListener("DOMContentLoaded", () => {
  const botaoTodas = document.querySelectorAll(".btn-filtro")[0];
  if (botaoTodas) filtrarCategoria("todas", botaoTodas);
});

function carregarDetalhesDoLivro() {
  const parametrosUrl = new URLSearchParams(window.location.search);
  const idLivro = parametrosUrl.get("id");

  if (!idLivro || !bancoDeLivros[idLivro]) {
    window.location.href = "books.html";
    return;
  }

  const dados = bancoDeLivros[idLivro];

  document.getElementById("livro-capa").src = dados.imagem;
  document.getElementById("livro-titulo").innerHTML = dados.titulo;
  document.getElementById("livro-descricao").innerHTML = dados.descricao;
  document.getElementById("link-amazon").href = dados.links.amazon;
  document.getElementById("link-editora").href = dados.links.editora;

  const prefacioContainer = document.getElementById("livro-prefacio-container");
  const imagensContainer = document.getElementById("livro-prefacio-imagens");

  imagensContainer.innerHTML = "";

  if (
    dados.prefacio &&
    dados.prefacio.imagens &&
    dados.prefacio.imagens.length > 0
  ) {
    document.getElementById("livro-prefacio-autor").textContent =
      dados.prefacio.autor;

    dados.prefacio.imagens.forEach((caminhoDaImagem) => {
      const img = document.createElement("img");
      img.src = caminhoDaImagem;
      img.alt = "Página do prefácio";
      imagensContainer.appendChild(img);
    });

    prefacioContainer.style.display = "block";
  } else {
    prefacioContainer.style.display = "none";
  }
}

window.addEventListener("DOMContentLoaded", () => {
  if (document.getElementById("livro-capa")) {
    carregarDetalhesDoLivro();
  }
});

function filtrarCategoriaCurso(categoria, botaoClicado) {
  const botoes = document.querySelectorAll(".btn-filtro");
  botoes.forEach((btn) => btn.classList.remove("ativo"));
  botaoClicado.classList.add("ativo");

  const cursos = document.querySelectorAll(".curso-item");
  const noCourse = document.querySelector(".noCourse");

  let temAlgumVisivel = false;

  cursos.forEach((curso) => {
    let catItem = curso.getAttribute("data-categoria");

    if (categoria === "todas" || catItem === categoria) {
      curso.style.display = "";
      temAlgumVisivel = true;
    } else {
      curso.style.display = "none";
    }
  });

  if (!temAlgumVisivel) {
    noCourse.style.display = "block";
  } else if (noCourse) {
    noCourse.style.display = "none";
  }

  const inputBusca = document.getElementById("buscaCurso");
  if (inputBusca) inputBusca.value = "";

  verificarGruposVaziosCursos();
}

function filtrarCursos() {
  const input = document.getElementById("buscaCurso");
  const filtro = input.value.toLowerCase();
  const cursos = document.querySelectorAll(".curso-item");
  const noCourse = document.querySelector(".noCourse");

  let temAlgumVisivel = false;

  cursos.forEach((curso) => {
    const textoCurso = curso.textContent.toLowerCase();

    if (textoCurso.includes(filtro)) {
      curso.style.display = "";
      temAlgumVisivel = true;
    } else {
      curso.style.display = "none";
    }
  });

  if (!temAlgumVisivel && noCourse) {
    noCourse.style.display = "block";
  } else if (noCourse) {
    noCourse.style.display = "none";
  }

  const botoes = document.querySelectorAll(".btn-filtro");
  botoes.forEach((btn) => btn.classList.remove("ativo"));
  if (botoes.length > 0) botoes[0].classList.add("ativo");

  verificarGruposVaziosCursos();
}

function verificarGruposVaziosCursos() {
  const grupos = document.querySelectorAll(".grupo-cursos");

  grupos.forEach((grupo) => {
    const cursosDesteGrupo = Array.from(grupo.querySelectorAll(".curso-item"));
    const temVisivel = cursosDesteGrupo.some(
      (curso) => curso.style.display !== "none",
    );

    if (temVisivel) {
      grupo.style.display = "block";
    } else {
      grupo.style.display = "none";
    }
  });
}

function abrirLightbox(caminhoDaImagem) {
  const modal = document.getElementById("meuLightbox");
  const imgAmpliada = document.getElementById("img-ampliada");

  if (modal && imgAmpliada) {
    modal.style.display = "block";
    imgAmpliada.src = caminhoDaImagem;
  }
}

function fecharLightbox() {
  const modal = document.getElementById("meuLightbox");
  if (modal) {
    modal.style.display = "none";
  }
}

window.addEventListener("DOMContentLoaded", () => {
  const imagens = document.querySelectorAll(".zoom-img");

  imagens.forEach((img) => {
    img.addEventListener("click", function () {
      abrirLightbox(this.src);
    });
  });
});

window.addEventListener("DOMContentLoaded", () => {
  const linksMenu = document.querySelectorAll(".nav__list a");
  const urlAtual = window.location.href;

  linksMenu.forEach((link) => {
    link.classList.remove("ativo_menu");

    const ehMatchExato = urlAtual === link.href;

    const ehPaginaInicial =
      urlAtual.endsWith("/") && link.href.endsWith("index.html");

    const ehSubRotaPublicacoes =
      urlAtual.includes("tutorial") && link.href.includes("publications.html");

    if (ehMatchExato || ehPaginaInicial || ehSubRotaPublicacoes) {
      link.classList.add("ativo_menu");
    }
  });
});
